<?php
/**
 * WooCommerce Classic Frontend Product & Archive Image Integration.
 *
 * @package WPCalibrate\ExternalProductImages
 */

declare(strict_types=1);

namespace WPCalibrate\ExternalProductImages\WooCommerce;

use WPCalibrate\ExternalProductImages\Images\ImageResolver;
use WPCalibrate\ExternalProductImages\Images\ImageRenderer;
use WPCalibrate\ExternalProductImages\Settings\Settings;

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/**
 * Filters standard WooCommerce product image outputs for archives, widgets, and loops.
 */
class ProductIntegration {

	/**
	 * Initialize hooks.
	 *
	 * @return void
	 */
	public function init(): void {
		// Hook native WooCommerce product image getter filter.
		add_filter( 'woocommerce_product_get_image', [ $this, 'filter_product_get_image' ], 10, 5 );

		// Fallback for post thumbnail html when called directly within product context.
		add_filter( 'post_thumbnail_html', [ $this, 'filter_post_thumbnail_html' ], 10, 5 );
	}

	/**
	 * Filter image HTML generated by $product->get_image().
	 *
	 * @param string               $image Existing image HTML.
	 * @param \WC_Product          $product Product instance.
	 * @param string|int[]         $size Image size.
	 * @param array<string, mixed> $attr HTML attributes.
	 * @param bool                 $placeholder Whether to use placeholder.
	 * @return string Filtered HTML image tag.
	 */
	public function filter_product_get_image( string $image, \WC_Product $product, $size, array $attr, bool $placeholder ): string {
		$plugin_enabled = (bool) Settings::get( 'enabled', true );
		if ( ! $plugin_enabled ) {
			return $image;
		}

		$size_name = is_string( $size ) ? $size : 'woocommerce_thumbnail';
		$resolved  = ImageResolver::resolve_product_image( $product->get_id(), $size_name );

		// Only override if resolved to an external URL or cached copy.
		if ( 'external_direct' === $resolved['source_type'] || 'cached_attachment' === $resolved['source_type'] ) {
			return ImageRenderer::render_tag( $resolved, $attr );
		}

		// Otherwise preserve default WooCommerce rendering.
		return $image;
	}

	/**
	 * Filter get_the_post_thumbnail() when called in a WooCommerce product loop.
	 *
	 * @param string       $html Existing thumbnail HTML.
	 * @param int          $post_id Post ID.
	 * @param int          $post_thumbnail_id Thumbnail attachment ID.
	 * @param string|int[] $size Image size.
	 * @param array<string, mixed> $attr HTML attributes.
	 * @return string Filtered HTML.
	 */
	public function filter_post_thumbnail_html( string $html, int $post_id, int $post_thumbnail_id, $size, array $attr ): string {
		// Strictly confine to product post types.
		if ( 'product' !== get_post_type( $post_id ) ) {
			return $html;
		}

		$plugin_enabled = (bool) Settings::get( 'enabled', true );
		if ( ! $plugin_enabled ) {
			return $html;
		}

		$size_name = is_string( $size ) ? $size : 'woocommerce_thumbnail';
		$resolved  = ImageResolver::resolve_product_image( $post_id, $size_name );

		if ( 'external_direct' === $resolved['source_type'] ) {
			return ImageRenderer::render_tag( $resolved, (array) $attr );
		}

		return $html;
	}
}
